'use strict';
// Zero-dependency build.
//
// Bundles the CommonJS source modules under src/ into self-contained IIFE bundles and
// assembles the loadable extension in dist/. Source modules use plain require()/module.exports,
// which also lets Node run them directly in tests/. The tiny bundler below only needs to know
// the module map and the entry points — no string rewriting of module bodies.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const VERSION = require('./src/version.js');

// module id (path under src/, no extension) -> source file
const MODULES = {
  'version': 'version.js',
  'background': 'background.js',
  'shared/core': 'shared/core.js',
  'shared/settings': 'shared/settings.js',
  'shared/presentation': 'shared/presentation.js',
  'shared/store': 'shared/store.js',
  'shared/transport': 'shared/transport.js',
  'shared/handle': 'shared/handle.js',
  'shared/config': 'shared/config.js',
  'shared/tweet': 'shared/tweet.js',
  'shared/analytics': 'shared/analytics.js',
  'shared/opportunity': 'shared/opportunity.js',
  'shared/reply': 'shared/reply.js',
  'shared/ai-client': 'shared/ai-client.js',
  'shared/opportunity-store': 'shared/opportunity-store.js',
  'shared/exporter': 'shared/exporter.js',
  'shared/favorites': 'shared/favorites.js',
  'content/dom': 'content/dom.js',
  'content/post-context': 'content/post-context.js',
  'content/tooltip': 'content/tooltip.js',
  'content/badge': 'content/badge.js',
  'content/layout': 'content/layout.js',
  'content/observer': 'content/observer.js',
  'content/diagnostics': 'content/diagnostics.js',
  'content/opportunity-ui': 'content/opportunity-ui.js',
  'content/reply-ui': 'content/reply-ui.js',
  'content/index': 'content/index.js',
  'popup/ai-connection': 'popup/ai-connection.js',
  'popup/demand-ui': 'popup/demand-ui.js',
  'popup/index': 'popup/index.js',
  'preview/index': 'preview/index.js'
};

const ENTRIES = {
  'background.js': 'background',
  'content.bundle.js': 'content/index',
  'popup.bundle.js': 'popup/index',
  'preview.bundle.js': 'preview/index'
};

function read(rel) {
  return fs.readFileSync(path.join(SRC, rel), 'utf8');
}

function resolve(fromId, request) {
  const parts = fromId.split('/');
  parts.pop(); // drop the file, keep its directory
  for (const seg of request.replace(/\.js$/, '').split('/')) {
    if (seg === '.' || seg === '') continue;
    if (seg === '..') parts.pop();
    else parts.push(seg);
  }
  const id = parts.join('/');
  if (!(id in MODULES)) throw new Error('Unknown module "' + id + '" required by "' + fromId + '"');
  return id;
}

function bundle(entryId) {
  const seen = new Set();
  (function visit(id) {
    if (seen.has(id)) return;
    seen.add(id);
    const source = read(MODULES[id]);
    for (const m of source.matchAll(/require\(['"]([^'"]+)['"]\)/g)) visit(resolve(id, m[1]));
  })(entryId);

  const factories = [...seen].map(id =>
    JSON.stringify(id) + ': function(require, module, exports) {\n' + read(MODULES[id]) + '\n}'
  );

  return [
    '// Generated by node build.cjs. Do not edit by hand; edit files under src/ and rebuild.',
    '(() => {',
    "'use strict';",
    'const __modules = {',
    factories.join(',\n'),
    '};',
    'const __cache = {};',
    'function __resolve(fromId, request) {',
    "  const parts = fromId.split('/');",
    '  parts.pop();',
    "  for (const seg of request.replace(/\\.js$/, '').split('/')) {",
    "    if (seg === '.' || seg === '') continue;",
    "    if (seg === '..') parts.pop();",
    '    else parts.push(seg);',
    '  }',
    "  return parts.join('/');",
    '}',
    'function __load(id) {',
    '  const mod = __cache[id] || (__cache[id] = { exports: {} });',
    '  if (mod.loaded) return mod.exports;',
    '  mod.loaded = true;',
    '  __modules[id]((request) => __load(__resolve(id, request)), mod, mod.exports);',
    '  return mod.exports;',
    '}',
    '__load(' + JSON.stringify(entryId) + ');',
    '})();',
    ''
  ].join('\n');
}

function copyFile(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function build() {
  fs.rmSync(DIST, { recursive: true, force: true });
  fs.mkdirSync(DIST, { recursive: true });

  // manifest with version injected from the single source of truth (src/version.js)
  const manifest = JSON.parse(read('manifest.json'));
  manifest.version = VERSION;
  fs.writeFileSync(path.join(DIST, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

  // bundles
  for (const [file, entry] of Object.entries(ENTRIES)) {
    fs.writeFileSync(path.join(DIST, file), bundle(entry));
  }

  // standalone page-world script (not bundled)
  fs.writeFileSync(path.join(DIST, 'bridge.js'), read('page/bridge.js').replace('__XPULSE_VERSION__', VERSION));

  // styles & html
  copyFile(path.join(SRC, 'styles/content.css'), path.join(DIST, 'content.css'));
  copyFile(path.join(SRC, 'popup/popup.html'), path.join(DIST, 'popup.html'));
  copyFile(path.join(SRC, 'popup/popup.css'), path.join(DIST, 'popup.css'));
  copyFile(path.join(SRC, 'preview/preview.html'), path.join(DIST, 'preview.html'));

  // icons
  fs.cpSync(path.join(ROOT, 'icons'), path.join(DIST, 'icons'), { recursive: true });

  console.log('Built dist/ (version ' + VERSION + '):');
  for (const file of Object.keys(ENTRIES)) console.log('  ' + file);
  console.log('  manifest.json, background.js, bridge.js, popup.html, preview.html, *.css, icons/');
}

build();
